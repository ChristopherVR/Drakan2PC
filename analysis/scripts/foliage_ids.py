"""Regenerate the vegetation resource-id table used by the living-foliage option.

  python -I analysis/scripts/lvl_objects.py --iso "<game>.iso" --level LEVEL1NA     # once per level -> build/lvl-objects
  python -I analysis/scripts/foliage_ids.py                                         # -> drakan_foliage_ids.inc

The runtime knows a placed object only by its resource id (record +0 of the resource db, the `res_id` of the level
object list; the low 16 bits are the class within the level's ODB, the high bits the ODB, so the same stem can mean two
different things in two levels and the table keeps the full id). Names come from the level object list; the table only
carries the ids and a kind (0 = tree, 1 = grass / flowers / ferns / crops), never names or game data.
"""

import argparse
import json
import re
import sys
from pathlib import Path

DECOMP = Path(__file__).resolve().parents[2]
DEFAULT_IN = DECOMP / "build" / "lvl-objects"
DEFAULT_OUT = DECOMP / "ps2recomp" / "ps2xRuntime" / "src" / "lib" / "drakan_foliage_ids.inc"

# Static prop classes only: 0x100d3 / 0x100d8 (level pieces), 0x10011 (a few trees). Triggers, sconces and
# platforms that merely have "tree" in their name are other classes and are left out.
CLASSES = {"0x100d3", "0x100d8", "0x10011"}
TREE = re.compile(
    r"^(Birch Tree \d+|Pine Tree \d+|Snowy Pine|High Res Tree_.*|Tree (Small|Large) \d+ Base|TreeHuge\d+_Op|"
    r"Evil Tree( wo eyes)?)$",
    re.I,
)
PLANT = re.compile(
    r"^(Grass \(Sod\)|Grass \d+ \d+ circ|Grass Plant|Flower \d+|corn\d*|fern|PlantGreen|royalplant\d+|bushthang\d+)$",
    re.I,
)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--objects", type=Path, default=DEFAULT_IN, help="folder with the lvl_objects.py JSON files")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    files = sorted(args.objects.glob("*.json"))
    if not files:
        print(f"no level object lists in {args.objects}; run lvl_objects.py first", file=sys.stderr)
        return 1
    found: dict[int, int] = {}
    counts = {0: 0, 1: 0}
    for f in files:
        for o in json.loads(f.read_text(encoding="utf-8"))["objects"]:
            if o.get("runtime_class") not in CLASSES:
                continue
            name = o.get("name") or ""
            kind = 0 if TREE.match(name) else 1 if PLANT.match(name) else None
            if kind is None:
                continue
            rid = int(o["res_id"], 16)
            if found.setdefault(rid, kind) != kind:
                print(f"conflicting kinds for {rid:#x} ({name})", file=sys.stderr)
                return 1
            counts[kind] += 1
    lines = [
        "// Generated by analysis/scripts/foliage_ids.py from the level object lists; do not edit.",
        "// {resource id, kind}: kind 0 = tree, 1 = grass / flowers / ferns / crops.",
    ]
    lines += [f"{{0x{rid:x}u, {kind}}}," for rid, kind in sorted(found.items())]
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(found)} ids ({counts[0]} tree, {counts[1]} plant placements) from {len(files)} levels -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
