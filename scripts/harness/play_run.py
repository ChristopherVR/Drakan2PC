"""Scripted game run without save games: New Game on a fresh, empty memory card, optionally in another level, with
renderer screenshots.

    python scripts/harness/play_run.py --name surdana
    python scripts/harness/play_run.py --name raven --level ravenshold --shots 0,300
    python scripts/harness/play_run.py --name walk --recipe scripts/harness/recipes/fps_movement_wall.txt
    python scripts/harness/play_run.py --name nodlss --env DRAKAN_DLSS=off --env DRAKAN_HD_TEXTURES=0
    python scripts/harness/play_run.py --list-levels
    python scripts/harness/play_run.py --name levelsave --level-save --recipe scripts/harness/recipes/level_save_mouse.txt

How it gets into a level (docs/reference/input.md, "Test runs without a save"):
  * DRAKAN_MEMCARD_DIR points the game at an empty card in the run folder, so the title menu's Cross is New Game and
    the player's cards are never read or written;
  * DRAKAN_AUTOPRESS + DRAKAN_INPUT_AUTOSTART tap Start/Cross through the menus and the intro cut scene and stop once
    Rynn is under control;
  * DRAKAN_START_LEVEL makes the first level after the intro load the chosen level instead (`--level`);
  * the input script's `shot <label>` writes <label>.png from the renderer; `--save` starts from a copy of a card
    instead (e.g. a relocated fixture from combat_save_fixture.py);
  * `--level-save` sets DRAKAN_TEST_LEVEL_SAVE: every save screen opens in the mode of the save offered at a level
    change (save screen mode 1), so the recipe reaches it through the pause menu's Save Game; menu mouse clicks are
    logged (DRAKAN_MENU_MOUSE_LOG) and `sync screen 5` waits for the save screen.

Runs the exe in dist/DrakanPC (its drakan.ini, HD textures and DLSS files), keeps logs in the run folder
(DRAKAN_LOG_DIR) and the game's own options file there too (DRAKAN_NATIVE_OPTIONS_INI, a copy of the player's), and retries when the game hangs before the script's `quit`. Output: build/harness/<name>/.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# Long level names as the disc and the engine use them (folder and file stem under English/Levels).
LEVELS = [
    "Level 1A - Surdana",
    "Level 1B - Kragmor",
    "Level 1C - Catacombs",
    "Level 1D - City of the Damned",
    "Level 1E - Inquisitor's Lair",
    "Level 2 - Shadowmire",
    "Level 3A - Andrellian Isles",
    "Level 3B - Crystal Mine",
    "Level 4A - Ravenshold",
    "Level 4B - Northern Tundra",
    "Level 5 - Shiverbane",
    "Level 6 - Valley of the Fallen",
    "Level 6 - Transition to Desert",
    "Level 8 - Stratos",
]


def resolve_level(text: str) -> str:
    """Exact name, level code ("4a", "2") or a unique case-insensitive part of the name ("raven")."""
    want = text.strip().lower()
    for name in LEVELS:
        code = name.split(" - ")[0][len("Level ") :].lower()
        if want in (name.lower(), code):
            return name
    hits = [name for name in LEVELS if want in name.lower()]
    if len(hits) == 1:
        return hits[0]
    raise SystemExit(f"level {text!r} matches {hits or 'nothing'}; --list-levels shows the names")


def build_recipe(shots: list[int]) -> str:
    lines = ["# generated by play_run.py; frame numbers count input samples after `sync`", "0 sync play 60"]
    at = 0
    for i, frame in enumerate(shots):
        at = max(at + 1, frame)
        lines.append(f"{at} shot shot{i}_{frame}")
    lines.append(f"{at + 10} quit")
    return "\n".join(lines) + "\n"


def run_once(exe: Path, env: dict[str, str], out: Path, timeout: float, attempt: int) -> bool:
    log = out / f"stdout_{attempt}.log"
    with log.open("wb") as f:
        proc = subprocess.Popen([str(exe)], cwd=exe.parent, env=env, stdout=f, stderr=subprocess.STDOUT)
        try:
            proc.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()
            print(f"attempt {attempt}: timed out after {timeout:.0f} s")
            return False
    text = log.read_bytes().decode("latin-1")
    if proc.returncode != 0 or "[in] script quit" not in text:
        print(f"attempt {attempt}: exit {proc.returncode}; a clean scripted quit is required")
        return False
    print(f"attempt {attempt}: ok (exit {proc.returncode})")
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", default="play", help="run folder name under --out-root (replaced if it exists)")
    ap.add_argument("--out-root", type=Path, default=ROOT / "build" / "harness")
    ap.add_argument("--exe", type=Path, default=ROOT / "dist" / "DrakanPC" / "drakan.exe")
    ap.add_argument("--level", help="start level instead of Level 1A - Surdana (name, code like 4a, or part)")
    ap.add_argument("--shots", default="0,120", help="screenshot frames after gameplay starts (generated recipe)")
    ap.add_argument("--recipe", type=Path, help="own input script instead of the generated one (must end in quit)")
    ap.add_argument("--save", type=Path, help="memory card folder (mc0) to copy into the run instead of an empty one")
    ap.add_argument("--env", action="append", default=[], help="extra KEY=VALUE for the game (repeatable)")
    ap.add_argument("--audio", action="store_true", help="keep audio on (off by default)")
    ap.add_argument("--timeout", type=float, default=300, help="seconds per attempt")
    ap.add_argument("--attempts", type=int, default=3)
    ap.add_argument("--level-save", action="store_true", help="stop at the level-change save screen (see above)")
    ap.add_argument("--list-levels", action="store_true")
    a = ap.parse_args()

    if a.list_levels:
        print("\n".join(LEVELS))
        return 0
    if not a.exe.is_file():
        raise SystemExit(f"{a.exe} not found; build with scripts/buildtool/Build-LocalGame.ps1 first")

    out = a.out_root / a.name
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    if a.recipe:
        recipe = a.recipe.read_text(encoding="utf-8")
    else:
        shots = [int(v) for v in a.shots.split(",") if v.strip()]
        recipe = build_recipe(shots)
    (out / "recipe.txt").write_text(recipe, encoding="utf-8")

    env = dict(os.environ)
    env.update(
        {
            "DRAKAN_INPUT_SCRIPT": str(out / "recipe.txt"),
            "DRAKAN_SHOT_DIR": str(out),
            "DRAKAN_LOG_DIR": str(out),
            "DRAKAN_AUTOPRESS": "3000",
            "DRAKAN_AUTOPRESS_UNTIL": str(int(a.timeout * 1000)),
            "DRAKAN_INPUT_AUTOSTART": "1",
            "PS2X_MAX_SECONDS": str(int(a.timeout)),
            # shown behind the other windows and never activated: a run does not take the foreground from the user
            "DRAKAN_NO_ACTIVATE": "1",
        }
    )
    if not a.audio:
        env["DRAKAN_AUDIO"] = "0"
    if a.level:
        env["DRAKAN_START_LEVEL"] = resolve_level(a.level)
    if a.level_save:
        env["DRAKAN_TEST_LEVEL_SAVE"] = "1"
        env["DRAKAN_MENU_MOUSE_LOG"] = "1"
    for kv in a.env:
        key, sep, value = kv.partition("=")
        if not sep:
            raise SystemExit(f"--env {kv!r}: expected KEY=VALUE")
        env[key] = value
    if "DRAKAN_NATIVE_OPTIONS_INI" not in env:
        # The game saves its own options (volume, subtitles, scheme ...) whenever they change: into a copy in the run
        # folder, never into the player's dist/DrakanPC/drakan_native_options.ini.
        options = out / "drakan_native_options.ini"
        player = a.exe.parent / "drakan_native_options.ini"
        if player.is_file():
            shutil.copyfile(player, options)
        env["DRAKAN_NATIVE_OPTIONS_INI"] = str(options)

    for attempt in range(1, a.attempts + 1):
        card = out / "card"
        if card.exists():
            shutil.rmtree(card)
        if a.save:
            shutil.copytree(a.save, card / "mc0")
        else:
            (card / "mc0").mkdir(parents=True)
        env["DRAKAN_MEMCARD_DIR"] = str(card / "mc0")
        t0 = time.monotonic()
        if run_once(a.exe, env, out, a.timeout + 30, attempt):
            pngs = sorted(p.name for p in out.glob("*.png"))
            print(f"{time.monotonic() - t0:.0f} s; {out}: {', '.join(pngs) or 'no screenshots'}")
            return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
