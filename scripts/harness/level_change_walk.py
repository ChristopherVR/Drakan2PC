"""Real walk-in level exit: Rynn is placed on (or near) an exit trigger of Surdana (DRAKAN_PLAYTEST_POS, drakan_playtest.cpp), the
recipe holds W until the game raises the level-change save screen (screen 5; the touch event 0x1001 -> queue -> save
screen path of docs/journal/2026-10-31/level-change.md), confirms it and follows the loading screen into the new level.

    python scripts/harness/level_change_walk.py --exit city
    python scripts/harness/level_change_walk.py --exit 441344,508928 --dist 8000 --bearing -90

--exit: a name (city, lair, shadowmire, ...) or "x,z" of the exit trigger (world units), `--dist` units away from it on
`--bearing` degrees (0 = +x, 90 = +z). W walks where the camera looks, which after the placement is +z (Rynn's start
camera), so the default bearing -90 puts the start due -z of the exit. y is `--y` (the ground height at the exit, dropped
a little). Output build/harness/<prefix>-walk-<exit>/ (stdout_1.log, shots); the verdict is printed:
walk-in touched the trigger (save screen opened), the loading screen, the level that loaded, the arrival position.
Does not touch the player's saves (private memory card, see play_run.py).
"""

from __future__ import annotations

import argparse
import math
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "harness"))
import netplay_two_instances as net  # noqa: E402

# Surdana exits seen in the log (x, ground y, z), see level-change.md section 7.
EXITS = {
    "city": (157696, 192890, 428032),
    "lair": (441344, 150248, 508928),
    "shadowmire": (521216, 150046, 447488),
    "catacombs": (508928, 151450, 791552),
    "kragmor": (729088, 152978, 772096),
}

RECIPE = """# walk-in generated by level_change_walk.py (times in ms: input samples run slower than world ticks)
clock milliseconds
0 sync play 60
{settle} key down W
{walk}
0 sync screen 5 3
0 key up W
0 key up S
50 shot save_screen
{confirm}
0 sync screen 26 2
50 shot loading
0 sync play 200
50 shot arrived
1000 quit
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exit", default="city", help="exit name or x,z")
    ap.add_argument(
        "--dist",
        type=float,
        default=0,
        help="start distance from the trigger (0: on it, walk out with W and back in with S)",
    )
    ap.add_argument("--out-ms", type=int, default=2500, help="ms W is held before walking back (dist 0 only)")
    ap.add_argument(
        "--bearing", type=float, default=-90, help="start direction from the trigger, degrees (0 = +x, 90 = +z)"
    )
    ap.add_argument(
        "--face",
        action="store_true",
        help="also write a heading toward the exit (the camera, not the heading, steers W)",
    )
    ap.add_argument("--y", type=float, help="start height (default: exit ground y + 300)")
    ap.add_argument(
        "--settle", type=int, default=6000, help="ms between 'play' and the first step (the placement needs about 5 s)"
    )
    ap.add_argument(
        "--confirm", default="20 pad tap CROSS\n60 pad tap CROSS\n100 pad tap CROSS", help="save screen input"
    )
    ap.add_argument("--exe", type=Path, default=ROOT / "build" / "final-game" / "bin" / "drakan.exe")
    ap.add_argument("--src", type=Path, default=ROOT / "dist" / "DrakanPC")
    ap.add_argument("--prefix", default="lcw")
    ap.add_argument("--timeout", type=int, default=420)
    ap.add_argument("--env", action="append", default=[])
    a = ap.parse_args()

    if a.exit in EXITS:
        ex, ey, ez = EXITS[a.exit]
    else:
        ex, ez = (float(v) for v in a.exit.split(","))
        ey = 0.0
    sy = a.y if a.y is not None else ey + 300
    b = math.radians(a.bearing)
    sx, sz = ex + a.dist * math.cos(b), ez + a.dist * math.sin(b)
    vx, vz = ex - sx, ez - sz
    yaw = math.atan2(-vz, vx)  # 0 faces +x, positive turns toward -z (drakan_playtest.h)
    name = f"{a.prefix}-walk-{a.exit.replace(',', '_')}"
    exe = net.prepare_folder(a.src, a.exe, ROOT / "build" / f"{a.prefix}-play")
    t1 = a.settle + a.out_ms  # times are absolute from the last sync
    walk = f"{t1} key up W" + chr(10) + f"{t1 + 100} key down S" if a.dist == 0 else f"{a.settle + 500} shot walking"
    recipe = ROOT / "build" / "harness" / f"{name}-recipe.txt"
    recipe.parent.mkdir(parents=True, exist_ok=True)
    recipe.write_text(RECIPE.format(settle=a.settle, confirm=a.confirm, walk=walk), encoding="utf-8", newline="\n")
    cmd = [
        sys.executable, str(ROOT / "scripts" / "harness" / "play_run.py"),
        "--name", name, "--exe", str(exe), "--recipe", str(recipe), "--timeout", str(a.timeout), "--attempts", "1",
        "--env", f"DRAKAN_PLAYTEST_POS={sx:.0f} {sy:.0f} {sz:.0f}" + (f" {yaw:.4f}" if a.face else ""),
        "--env", "DRAKAN_LEVELCHANGE=99@100000000",  # arms the arrival report / exit list only (step 99 never fires)
        "--env", "DRAKAN_LIFECYCLE_LOG=1", "--env", "DRAKAN_WORLD=2",
    ]  # fmt: skip
    for extra in a.env:
        cmd += ["--env", extra]
    print(f"start {sx:.0f} {sy:.0f} {sz:.0f} yaw {yaw:.3f}, exit at {ex:.0f} {ey:.0f} {ez:.0f}")
    rc = subprocess.run(cmd, cwd=ROOT, stdout=subprocess.DEVNULL).returncode
    log = ROOT / "build" / "harness" / name / "stdout_1.log"
    text = log.read_text(encoding="latin-1") if log.is_file() else ""
    placed = re.findall(r"\[playtest\] (placed|gave up).*", text)
    taken = re.findall(r"\[levelchange\] exit taken in '(.*?)' at (\S+ \S+ \S+)", text)
    loads = re.findall(r"afterLevelLoad level='(.*?)' path=", text)[2:]
    arr = re.findall(r"arrival report '(.*?)' frame 200 player \w+ pos (\S+ \S+ \S+)", text)[2:]
    saves = re.findall(r"BeforeSaveWrite.*|beforeSaveWrite.*", text)
    print(f"placement: {placed or 'no [playtest] line'}")
    print(f"touched the trigger (exit taken, .rlt written): {taken or 'NO'}")
    print(f"loaded after the walk: {loads or 'nothing'}; arrival at frame 200: {arr or 'n/a'}")
    print(f"save events: {len(saves)}; clean quit: {rc == 0}; output build/harness/{name}")
    return 0 if taken and loads else 1


if __name__ == "__main__":
    sys.exit(main())
