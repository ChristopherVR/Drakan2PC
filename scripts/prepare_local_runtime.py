#!/usr/bin/env python3
"""Generate the private, git-ignored Drakan runtime inputs from an owned SCES_500.06 or SCUS_971.28 ELF.

Requires Python 3.11+. Writes two files into the in-repo ps2recomp/ tree (both are
listed in .gitignore and rejected by scripts/repository_guard.py if ever tracked):
  ps2xRuntime/src/lib/vu/aot/ps2_vu1_image.inc  the game's VU1 microcode image
  ps2xRuntime/src/res/drakan.ico                an original placeholder icon
An existing file is never overwritten. No game bytes are distributed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

DEFAULT_RUNTIME = Path(__file__).resolve().parents[1] / "ps2recomp"
ELF_SIZE = 4566488
ELF_SHA256 = "7d790b35733e3e7204df8db84f0ce55a81aa667d9b75c5f121066fc565883b8e"
VU_CHUNKS = ((4031504, 2048), (4033560, 2048), (4035616, 2048), (4037672, 2048), (4039728, 2048), (4041784, 1944))
REGIONS = Path(__file__).resolve().parent / "buildtool" / "regions.json"
VU_SHA256 = "8a2dceea21b39703cffa7456d8278d2824cd1852359a4488552131ce0aa623ad"
VU_FNV = 0xAEA998A337773D22
VU_RELATIVE = Path("ps2xRuntime/src/lib/vu/aot/ps2_vu1_image.inc")
ICON_RELATIVE = Path("ps2xRuntime/src/res/drakan.ico")


def known_executables() -> list[tuple[int, str, tuple]]:
    """(size, SHA-256, VU chunks) of every verified boot ELF: PAL above, other regions from regions.json.

    Both regions store the same VU1 microcode, only at different file offsets (docs/reference/regions.md).
    """
    known = [(ELF_SIZE, ELF_SHA256, VU_CHUNKS)]
    for profile in json.loads(REGIONS.read_text(encoding="utf-8"))["regions"].values():
        if profile["boot"] != "SCES_500.06":
            known.append((profile["elf_size"], profile["elf_sha256"], tuple(tuple(c) for c in profile["vu_chunks"])))
    return known


def matching_executable(elf: Path) -> tuple[str, tuple, bytes]:
    size = elf.stat().st_size
    candidates = [k for k in known_executables() if k[0] == size]
    if not candidates:
        raise ValueError("Unsupported ELF size; expected the verified PAL SCES_500.06 or USA SCUS_971.28")
    data = elf.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    for _, sha, chunks in candidates:
        if data[:6] == b"\x7fELF\x01\x01" and digest == sha:
            return sha, chunks, data
    raise ValueError("ELF SHA-256 differs from the verified executables; no output written")


def extract_vu(elf: Path) -> bytes:
    _, chunks, data = matching_executable(elf)
    if any(offset + size > len(data) for offset, size in chunks):
        raise ValueError("VU image range exceeds the ELF")
    image = b"".join(data[offset : offset + size] for offset, size in chunks)
    if len(image) != 12184 or hashlib.sha256(image).hexdigest() != VU_SHA256:
        raise ValueError("Reconstructed VU image failed size/SHA-256 verification")
    return image


def render_vu_include(image: bytes) -> bytes:
    """Match scripts/vu1_aot_image.py's output, without embedding its input."""
    if len(image) != 12184:
        raise ValueError("VU image must contain exactly 1523 instruction pairs")
    fnv = 0xCBF29CE484222325
    for byte in image:
        fnv = ((fnv ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    if fnv != VU_FNV:
        raise ValueError("VU image FNV-1a differs from the compiled AOT image")
    lines = [
        "// Generated by scripts/vu1_aot_image.py from analysis/vu/vu1_micromem.bin - do not edit.\n",
        "// One 64-bit word per instruction pair: lower instruction | upper instruction << 32 (as stored in VU1 micro memory).\n",
        "static constexpr uint32_t kVu1ImagePairs = 1523;\n",
        f"static constexpr uint64_t kVu1ImageHash = 0x{fnv:016x}ull;\n",
        "static constexpr uint64_t kVu1Image[1523] = {\n",
    ]
    for index, (word,) in enumerate(struct.iter_unpack("<Q", image)):
        lines.append(f"0x{word:016x}ull," + ("\n" if index % 4 == 3 else ""))
    lines.append("\n};\n")
    return "".join(lines).encode("ascii")


def original_icon() -> bytes:
    """Original abstract diamond icon, constructed as a 32-bit Windows DIB."""
    size = 32
    pixels = bytearray()
    mask = bytearray()
    for y in reversed(range(size)):  # ICO DIB scanlines are bottom-up
        mask_row = 0
        for x in range(size):
            distance = abs(x - 15.5) + abs(y - 15.5)
            opaque = distance < 15
            border = distance > 11
            rgba = (220, 240, 245, 255) if border else (30, 120, 145, 255)
            r, g, b, a = rgba if opaque else (0, 0, 0, 0)
            pixels.extend((b, g, r, a))
            if not opaque:
                mask_row |= 1 << (31 - x)
        mask.extend(mask_row.to_bytes(4, "big"))
    dib = struct.pack("<IiiHHIIiiII", 40, size, size * 2, 1, 32, 0, len(pixels), 0, 0, 0, 0) + pixels + mask
    return struct.pack("<HHH", 0, 1, 1) + struct.pack("<BBBBHHII", size, size, 0, 0, 1, 32, len(dib), 22) + dib


def checked_target(runtime: Path, relative: Path) -> Path:
    target = runtime / relative
    if target.is_symlink() or not target.resolve().is_relative_to(runtime):
        raise ValueError(f"Asset path escapes the runtime or is a symlink: {relative}")
    return target


def prepare_runtime(runtime: Path, elf: Path) -> dict:
    # Validate owned input and construct all outputs before touching the tree.
    image = extract_vu(elf)
    include = render_vu_include(image)
    runtime = runtime.absolute()
    if runtime.is_symlink():
        raise ValueError("runtime-source must be a real directory, not a symlink")
    runtime = runtime.resolve()
    for relative in (Path("ps2xRuntime/CMakeLists.txt"),):
        if not (runtime / relative).is_file():
            raise ValueError("Missing runtime CMake source; runtime-source must be the ps2recomp/ directory")
    vu_target = checked_target(runtime, VU_RELATIVE)
    icon_target = checked_target(runtime, ICON_RELATIVE)
    if not vu_target.parent.is_dir() or not icon_target.parent.is_dir():
        raise ValueError("Missing runtime asset directories under runtime-source")
    if vu_target.exists() and vu_target.read_bytes().replace(b"\r\n", b"\n") != include:
        raise ValueError("Existing VU include differs; refusing to overwrite it")
    if icon_target.exists() and not icon_target.is_file():
        raise ValueError("Icon path is not a regular file")
    created = []
    for target, data in ((vu_target, include), (icon_target, original_icon())):
        if target.exists():  # Existing icon/custom artwork is preserved verbatim.
            continue
        with target.open("xb") as stream:
            stream.write(data)
        created.append(target.relative_to(runtime).as_posix())
    return {
        "runtime_source": str(runtime),
        "elf_sha256": matching_executable(elf)[0],
        "vu_sha256": VU_SHA256,
        "vu_pairs": len(image) // 8,
        "vu_fnv1a": f"{VU_FNV:016x}",
        "created": created,
        "private_local_output": True,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--runtime-source", type=Path, default=DEFAULT_RUNTIME, help="the in-repo ps2recomp/ directory (default)"
    )
    parser.add_argument("--elf", type=Path, required=True, help="Owned, extracted SCES_500.06 or SCUS_971.28 ELF")
    args = parser.parse_args(argv)
    try:
        result = prepare_runtime(args.runtime_source, args.elf)
    except (OSError, ValueError) as exc:
        print(f"prepare_local_runtime: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
