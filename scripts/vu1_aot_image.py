#!/usr/bin/env python
"""Generate the VU1 microcode image used by the ahead-of-time compiled VU1 programs
(ps2recomp/ps2xRuntime/src/lib/vu/aot/ps2_vu1_image.inc) from analysis/vu/vu1_micromem.bin.
Usage: vu1_aot_image.py <vu1_micromem.bin> <out.inc>"""

import struct
import sys

data = open(sys.argv[1], "rb").read()
n = len(data) // 8
fnv = 0xCBF29CE484222325
for b in data[: n * 8]:
    fnv = ((fnv ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
with open(sys.argv[2], "w", newline="\n") as f:
    f.write("// Generated by scripts/vu1_aot_image.py from analysis/vu/vu1_micromem.bin - do not edit.\n")
    f.write(
        "// One 64-bit word per instruction pair: lower instruction | upper instruction << 32 (as stored in VU1 micro memory).\n"
    )
    f.write("static constexpr uint32_t kVu1ImagePairs = %d;\n" % n)
    f.write("static constexpr uint64_t kVu1ImageHash = 0x%016xull;\n" % fnv)
    f.write("static constexpr uint64_t kVu1Image[%d] = {\n" % n)
    for i in range(n):
        lo, hi = struct.unpack_from("<II", data, i * 8)
        f.write("0x%016xull," % (lo | (hi << 32)))
        if i % 4 == 3:
            f.write("\n")
    f.write("\n};\n")
print(n, "pairs, hash %016x" % fnv)
