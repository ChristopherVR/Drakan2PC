#pragma once
// Multiplayer map definitions ("arenas", the Drakan: Order of the Flame style dedicated deathmatch maps built from the
// terrain of a campaign level): a small INI text, committed in configs/mp_maps.ini (no game data, only numbers and
// names), extendable by the player (mp_maps.ini next to the exe) and by mod packs (maps/*.ini). Format and the rules of
// the arena world mode: docs/reference/netcode.md "Multiplayer maps". Std only; the game side is drakan_arena.
//
//   [arena surdana-meadow]            ; section name: "arena " + a short unique id
//   name = Surdana Meadow             ; shown in menus and sent as MatchConfig.level (<= 64 characters)
//   level = Level 1A - Surdana        ; the campaign / mod level whose terrain it uses (LEVELLST title)
//   description = ...
//   modes = dm, tdm                   ; dm (deathmatch), tdm (team deathmatch); default both
//   players = 8                       ; maximum number of players, 2..16
//   health = 100                      ; the start health bar in server points (the game scales it to Rynn's maximum)
//   bounds = x0 z0 x1 z1              ; playable rectangle in world units; leaving it for a few seconds is a respawn
//   loadout = 0x20abc 0x20abd         ; resource ids of items every player starts each life with (optional)
//   spawn = x y z yawDeg [team=N]             ; repeatable: where players appear (at least 2)
//   pickup = x y z respawnSec [res=0x2xxxx] [name=Label]   ; repeatable
//                                       without res: the level's own loose item nearest to (x, y, z) becomes the pickup
//                                       with res: that resource is spawned there (and at every respawn)
#include <array>
#include <cstdint>
#include <string>
#include <utility>
#include <vector>

namespace drakan::net {

struct ArenaSpawn {
    float pos[3] = {0, 0, 0};
    float yawDeg = 0;
    uint8_t team = 0; // 0 = any team, 1..4 (spawn = ... team=N)
};

// marker = base|flag|zone x y z [radius=R] [team=N] [name=Label]: objective positions for custom modes (authored; see
// GameModes.h). base: where a team brings a flag; flag: a flag's home; zone: a hold area.
struct ArenaMarker {
    enum class Kind : uint8_t { Base, Flag, Zone };
    Kind kind = Kind::Zone;
    float pos[3] = {0, 0, 0};
    float radius = 600;
    uint8_t team = 0;
    std::string label;
};

struct ArenaPickup {
    float pos[3] = {0, 0, 0};
    uint32_t respawnSec = 30;
    uint32_t resId = 0; // 0 = adopt the level's loose item nearest to pos
    std::string label;
};

struct ArenaDef {
    std::string id;    // "surdana-meadow"
    std::string name;  // display name, also the value of MatchConfig.level
    std::string level; // base level (a disc level title or a mod pack level)
    std::string description;
    std::string source; // "built-in", a file path or "mod <id>"
    std::string game;   // "Drakan 1" (Order of the Flame) / "Drakan 2" (the disc): the menu tag; empty = untagged
    bool deathmatch = true;
    bool teamDeathmatch = true;
    uint8_t maxPlayers = 8;
    uint16_t startHealth = 100;
    bool hasBounds = false;
    float bounds[4] = {0, 0, 0, 0}; // minX, minZ, maxX, maxZ
    std::vector<uint32_t> loadout;
    std::vector<ArenaSpawn> spawns;
    std::vector<ArenaPickup> pickups;
    std::vector<ArenaMarker> markers;
    // keep = x y z / remove = x y z: per-object overrides of the arena world filter at a world position (authored only,
    // the game's filter does not read them yet).
    std::vector<std::array<float, 3>> keepAt, removeAt;
    std::vector<std::string> customModes; // ids from `modes =` other than dm / tdm (see GameModes.h)

    // Index of the spawn point that is farthest from every given position (xz distance), `avoid` excluded when another
    // choice exists; -1 when there are no spawns. Ties go to the lower index.
    int pickSpawn(const std::vector<std::pair<float, float>>& others, int avoid = -1) const;
    bool insideBounds(float x, float z) const;
};

class ArenaCatalog {
public:
    // Parses `text`; every valid arena is added (an existing id is replaced, so later sources win). Problems are
    // appended to `errors` as "<source>:<line>: message"; an invalid arena is dropped as a whole. Returns the number
    // of arenas added or replaced.
    // `defaultGame`: the `game` of arenas that do not say (a pack of a converted campaign passes "Drakan 1").
    size_t add(const std::string& text, const std::string& source, std::vector<std::string>* errors = nullptr,
               const std::string& defaultGame = std::string());
    const std::vector<ArenaDef>& arenas() const { return arenas_; }
    // By id or by display name, case-insensitive; null when unknown.
    const ArenaDef* find(const std::string& idOrName) const;
    void clear() { arenas_.clear(); }

private:
    std::vector<ArenaDef> arenas_;
};

// The arenas of configs/mp_maps.ini, compiled in (ArenaMapsBuiltin.cpp is generated by CMake from that file).
const std::string& builtinArenaText();

} // namespace drakan::net
