void setMenuLanguage(std::string_view name) {
    std::string key(name);
    for (char& c : key)
        c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    const auto language = key == "german"    ? MenuLanguage::German
                          : key == "french"  ? MenuLanguage::French
                          : key == "italian" ? MenuLanguage::Italian
                          : key == "spanish" ? MenuLanguage::Spanish
                                             : MenuLanguage::English;
    g_language.store(language, std::memory_order_relaxed);
}
MenuLanguage menuLanguage() {
    return g_language.load(std::memory_order_relaxed);
}
const char* menuText(std::string_view english) {
    const auto language = menuLanguage();
    for (const Entry& entry : kEntries) {
        if (english == entry.english)
            return language == MenuLanguage::English ? entry.english
                                                     : entry.translations[static_cast<size_t>(language) - 1];
    }
    // Only catalog keys/literals are accepted; unknown keys have a stable diagnostic fallback.
    return "[Missing menu text]";
}
std::string menuTextOrSelf(std::string_view text) {
    for (const Entry& entry : kEntries)
        if (text == entry.english)
            return menuText(text);
    return std::string(text);
}
std::string menuFormat(std::string_view english, std::initializer_list<std::string_view> arguments) {
    std::string result;
    const std::string_view pattern = menuText(english);
    const std::vector<std::string_view> args(arguments);
    for (size_t i = 0; i < pattern.size(); ++i) {
        if (pattern[i] == '{' && i + 2 < pattern.size() && pattern[i + 2] == '}' && pattern[i + 1] >= '0' &&
            pattern[i + 1] <= '9') {
            const size_t index = static_cast<size_t>(pattern[i + 1] - '0');
            if (index < args.size())
                result += args[index];
            i += 2;
        } else {
            result += pattern[i];
        }
    }
    return result;
}
