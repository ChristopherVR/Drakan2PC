"""Generate src/fmv_tables.inc from FFmpeg libavcodec/mpeg12data.c (LGPL). usage: python -I gen_tables.py mpeg12data.c out.inc"""

import re
import sys

s = open(sys.argv[1]).read()


def arr(n):
    return re.search(n + r"[^=]*=\s*\{(.*?)\};", s, re.S).group(1)


def pairs(n):
    return [(int(a, 16), int(b)) for a, b in re.findall(r"\{\s*(0x[0-9a-fA-F]+)\s*,\s*(\d+)\s*\}", arr(n))]


def ints(n):
    return [int(x) for x in re.findall(r"-?\d+", arr(n))]


def hx(n):
    return [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", arr(n))]


o = open(sys.argv[2], "w")
o.write(
    "// Generated by tools/gen_tables.py from FFmpeg libavcodec/mpeg12data.c (LGPL 2.1+, (c) FFmpeg contributors).\n// MPEG-1/2 VLC tables B.12-B.15. Do not edit.\n"
)


def emit(name, t, ty="int"):
    o.write("static const %s %s[%d] = {%s};\n" % (ty, name, len(t), ",".join(map(str, t))))


emit("kDcLumCode", hx("ff_mpeg12_vlc_dc_lum_code"))
emit("kDcLumBits", ints("ff_mpeg12_vlc_dc_lum_bits"))
emit("kDcChrCode", hx("ff_mpeg12_vlc_dc_chroma_code"))
emit("kDcChrBits", ints("ff_mpeg12_vlc_dc_chroma_bits"))
emit("kRun", ints("ff_mpeg12_run"))
emit("kLevel", ints("ff_mpeg12_level"))
for n, k in (("mpeg1", "kVlc1"), ("mpeg2", "kVlc2")):
    p = pairs("ff_%s_vlc_table" % n)
    emit(k + "Code", [a for a, b in p])
    emit(k + "Bits", [b for a, b in p])
